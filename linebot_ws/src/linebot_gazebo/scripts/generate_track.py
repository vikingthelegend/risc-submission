#!/usr/bin/env python3
"""Generate Gazebo Harmonic worlds containing a black line on a light floor.

Built-in shapes (written to worlds/<name>.sdf):
    straight  circle  oval  s_curve  square_loop  figure_eight

Your own paths:
    generate_track.py --name mytrack --csv path.csv [--closed] [--smooth 2] [--scale 1.0]
        CSV = two columns x,y in metres (optional header row).
    generate_track.py --name mytrack --image track.png --image-width 6.0 --start 0 0 0
        PNG/JPG of a black line on white, stretched over a floor that is --image-width m
        wide (height follows the aspect ratio).  --start x y yaw gives the spawn pose.

The line is a chain of thin, collision-free boxes, so it renders reliably in ogre2 and the
robot drives straight over it.  A start pose per track is merged into config/start_poses.yaml.

Usage:
    ros2 run linebot_gazebo generate_track.py --all         # (re)generate built-ins
    (or run directly from the source tree: ./scripts/generate_track.py --all)
"""
import argparse
import csv
import math
import os
import shutil
import sys

try:
    import yaml
except ImportError:      # PyYAML ships with ROS 2, but don't die without it
    yaml = None

LINE_WIDTH = 0.04        # m
STEP = 0.03              # m, spacing of the sampled path
Z = 0.001                # m, line box centre height (box is 2 mm thick)


# ----------------------------------------------------------------- path helpers
def arc(cx, cy, r, a0_deg, a1_deg, n=40):
    a0, a1 = math.radians(a0_deg), math.radians(a1_deg)
    return [(cx + r * math.cos(a0 + (a1 - a0) * k / n),
             cy + r * math.sin(a0 + (a1 - a0) * k / n)) for k in range(n + 1)]


def resample(pts, step=STEP, closed=False):
    """Evenly re-sample a polyline."""
    pts = list(pts)
    if closed and pts[0] != pts[-1]:
        pts.append(pts[0])
    out = [pts[0]]
    carry = 0.0
    for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
        seg = math.hypot(x1 - x0, y1 - y0)
        if seg == 0:
            continue
        d = step - carry
        while d <= seg:
            t = d / seg
            out.append((x0 + t * (x1 - x0), y0 + t * (y1 - y0)))
            d += step
        carry = seg - (d - step)
    if closed:
        out[-1] = out[0] if math.hypot(out[-1][0] - out[0][0], out[-1][1] - out[0][1]) < step else out[-1]
    return out


def chaikin(pts, iterations=2, closed=False):
    for _ in range(iterations):
        new = []
        n = len(pts)
        rng = range(n) if closed else range(n - 1)
        if not closed:
            new.append(pts[0])
        for i in rng:
            p, q = pts[i], pts[(i + 1) % n]
            new.append((0.75 * p[0] + 0.25 * q[0], 0.75 * p[1] + 0.25 * q[1]))
            new.append((0.25 * p[0] + 0.75 * q[0], 0.25 * p[1] + 0.75 * q[1]))
        if not closed:
            new.append(pts[-1])
        pts = new
    return pts


# ----------------------------------------------------------------- built-in shapes
def shape_straight(length=6.0):
    return [(0.0, 0.0), (length, 0.0)], False


def shape_circle(r=1.0):
    return [(r * math.sin(t), r - r * math.cos(t))
            for t in [2 * math.pi * k / 200 for k in range(201)]], True


def shape_oval(straight=2.0, r=0.8):
    pts = [(0.0, 0.0), (straight, 0.0)]
    pts += arc(straight, r, r, -90, 90)
    pts += [(straight, 2 * r), (0.0, 2 * r)]
    pts += arc(0.0, r, r, 90, 270)
    return pts, True


def shape_s_curve(length=8.0, amp=0.5, wavelength=4.0):
    n = 400
    return [(length * k / n, amp * math.sin(2 * math.pi * (length * k / n) / wavelength))
            for k in range(n + 1)], False


def shape_square_loop(side=2.5, r=0.4):
    pts = [(r, 0.0), (side - r, 0.0)]
    pts += arc(side - r, r, r, -90, 0)
    pts += [(side, side - r)]
    pts += arc(side - r, side - r, r, 0, 90)
    pts += [(r, side)]
    pts += arc(r, side - r, r, 90, 180)
    pts += [(0.0, r)]
    pts += arc(r, r, r, 180, 270)
    return pts, True


def shape_figure_eight(a=1.5):
    # lemniscate of Gerono, started on a lobe (not on the crossing)
    return [(a * math.sin(t), a * math.sin(t) * math.cos(t))
            for t in [math.pi / 2 + 2 * math.pi * k / 400 for k in range(401)]], True


SHAPES = {
    'straight': shape_straight, 'circle': shape_circle, 'oval': shape_oval,
    's_curve': shape_s_curve, 'square_loop': shape_square_loop,
    'figure_eight': shape_figure_eight,
}


# ----------------------------------------------------------------- SDF writing
SDF_HEAD = """<?xml version="1.0"?>
<!-- Generated by generate_track.py - edit the generator, not this file. -->
<sdf version="1.9">
  <world name="line_track">
    <physics name="1ms" type="ode">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>

    <scene>
      <ambient>0.7 0.7 0.7 1</ambient>
      <background>0.45 0.55 0.65 1</background>
      <shadows>false</shadows>
    </scene>
    <light type="directional" name="sun">
      <cast_shadows>false</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.8 0.8 0.8 1</diffuse>
      <specular>0 0 0 1</specular>
      <direction>-0.3 0.2 -1</direction>
    </light>
"""

GROUND_PLAIN = """
    <model name="ground">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>60 60</size></plane></geometry>
        </collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>60 60</size></plane></geometry>
          <material>
            <ambient>0.92 0.92 0.92 1</ambient><diffuse>0.92 0.92 0.92 1</diffuse>
            <specular>0 0 0 1</specular>
          </material>
        </visual>
      </link>
    </model>
"""

GROUND_TEXTURE = """
    <model name="ground">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>60 60</size></plane></geometry>
        </collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>{w:.3f} {h:.3f}</size></plane></geometry>
          <material>
            <ambient>1 1 1 1</ambient><diffuse>1 1 1 1</diffuse><specular>0 0 0 1</specular>
            <pbr><metal>
              <albedo_map>{tex}</albedo_map>
              <roughness>1.0</roughness><metalness>0.0</metalness>
            </metal></pbr>
          </material>
        </visual>
      </link>
    </model>
"""

LINE_MATERIAL = ('<material><ambient>0.02 0.02 0.02 1</ambient><diffuse>0.02 0.02 0.02 1</diffuse>'
                 '<specular>0 0 0 1</specular></material>')


def track_model(pts, closed, width=LINE_WIDTH):
    pts = list(pts)
    if closed:
        pts = pts + [pts[0]]
    visuals = []
    for i, ((x0, y0), (x1, y1)) in enumerate(zip(pts, pts[1:])):
        L = math.hypot(x1 - x0, y1 - y0)
        if L < 1e-6:
            continue
        yaw = math.atan2(y1 - y0, x1 - x0)
        visuals.append(
            f'        <visual name="s{i}"><pose>{(x0 + x1) / 2:.4f} {(y0 + y1) / 2:.4f} {Z} 0 0 {yaw:.4f}</pose>'
            f'<geometry><box><size>{L + width * 0.5:.4f} {width} 0.002</size></box></geometry>'
            f'{LINE_MATERIAL}</visual>')
    return ('\n    <model name="track">\n      <static>true</static>\n      <link name="link">\n'
            + '\n'.join(visuals) + '\n      </link>\n    </model>\n')


def start_pose(pts):
    k = min(3, len(pts) - 1)
    yaw = math.atan2(pts[k][1] - pts[0][1], pts[k][0] - pts[0][0])
    return {'x': round(pts[0][0], 3), 'y': round(pts[0][1], 3), 'yaw': round(yaw, 3)}


# ----------------------------------------------------------------- main
def pkg_dirs():
    root = os.path.abspath(os.path.join(os.path.dirname(os.path.realpath(__file__)), '..'))
    return os.path.join(root, 'worlds'), os.path.join(root, 'config', 'start_poses.yaml')


def update_poses(path, name, pose):
    if yaml is None:
        print(f'  (PyYAML missing - add manually: {name}: {pose})')
        return
    data = {}
    if os.path.exists(path):
        with open(path) as f:
            data = yaml.safe_load(f) or {}
    data[name] = pose
    with open(path, 'w') as f:
        f.write('# Spawn pose per track (metres, radians). Written by generate_track.py.\n')
        yaml.safe_dump(data, f, sort_keys=True, default_flow_style=False)


def write_world(worlds_dir, poses_file, name, pts, closed, texture=None, size=None, pose=None):
    if texture:
        w, h = size
        body = GROUND_TEXTURE.format(w=w, h=h, tex=texture)
    else:
        body = GROUND_PLAIN + track_model(pts, closed)
    path = os.path.join(worlds_dir, f'{name}.sdf')
    with open(path, 'w') as f:
        f.write(SDF_HEAD + body + '  </world>\n</sdf>\n')
    pose = pose or start_pose(pts)
    update_poses(poses_file, name, pose)
    print(f'wrote {path}  start={pose}')


def load_csv(path, scale):
    pts = []
    with open(path, newline='') as f:
        for row in csv.reader(f):
            try:
                pts.append((float(row[0]) * scale, float(row[1]) * scale))
            except (ValueError, IndexError):
                continue                       # header / blank line
    if len(pts) < 2:
        sys.exit(f'{path}: need at least 2 numeric x,y rows')
    return pts


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--all', action='store_true', help='generate every built-in shape')
    ap.add_argument('--shape', choices=sorted(SHAPES))
    ap.add_argument('--name', help='output world name (default: shape name)')
    ap.add_argument('--csv')
    ap.add_argument('--image')
    ap.add_argument('--image-width', type=float, default=6.0, help='floor width in m for --image')
    ap.add_argument('--start', nargs=3, type=float, metavar=('X', 'Y', 'YAW'))
    ap.add_argument('--closed', action='store_true', help='CSV path is a closed loop')
    ap.add_argument('--smooth', type=int, default=0, help='Chaikin smoothing iterations for CSV')
    ap.add_argument('--scale', type=float, default=1.0, help='scale factor for CSV coordinates')
    ap.add_argument('--out-dir', help='override worlds/ output directory')
    a = ap.parse_args()

    worlds_dir, poses_file = pkg_dirs()
    if a.out_dir:
        worlds_dir = a.out_dir
    os.makedirs(worlds_dir, exist_ok=True)
    os.makedirs(os.path.dirname(poses_file), exist_ok=True)

    if a.all:
        for name, fn in SHAPES.items():
            pts, closed = fn()
            write_world(worlds_dir, poses_file, name, resample(pts, STEP, closed), closed)
        return

    if a.image:
        if not a.name:
            sys.exit('--image needs --name')
        try:
            import cv2
            img = cv2.imread(a.image)
            ih, iw = img.shape[:2]
        except Exception:                      # noqa: BLE001
            sys.exit('could not read image (is python3-opencv installed?)')
        tex_dir = os.path.join(worlds_dir, 'textures')
        os.makedirs(tex_dir, exist_ok=True)
        fname = os.path.basename(a.image)
        shutil.copy(a.image, os.path.join(tex_dir, fname))
        size = (a.image_width, a.image_width * ih / iw)
        pose = dict(zip(('x', 'y', 'yaw'), a.start)) if a.start else {'x': 0.0, 'y': 0.0, 'yaw': 0.0}
        write_world(worlds_dir, poses_file, a.name, [(0, 0), (1, 0)], False,
                    texture=f'textures/{fname}', size=size, pose=pose)
        return

    if a.csv:
        if not a.name:
            sys.exit('--csv needs --name')
        pts = load_csv(a.csv, a.scale)
        if a.smooth:
            pts = chaikin(pts, a.smooth, a.closed)
        pts = resample(pts, STEP, a.closed)
        pose = dict(zip(('x', 'y', 'yaw'), a.start)) if a.start else None
        write_world(worlds_dir, poses_file, a.name, pts, a.closed, pose=pose)
        return

    if a.shape:
        pts, closed = SHAPES[a.shape]()
        write_world(worlds_dir, poses_file, a.name or a.shape, resample(pts, STEP, closed), closed)
        return

    ap.print_help()


if __name__ == '__main__':
    main()
